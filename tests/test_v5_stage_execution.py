class TestV5MagneticStage:
    """manual_promoted magnetic formulas must all be executed."""

    _PROMOTED = [
        "B_eff",
        "capture_j",
        "E_pulse",
        "E_ring",
        "E_level",
        "Entr",
        "R_hm_j",
        "conc_j",
        "tail_j",
    ]

    @pytest.mark.parametrize("lhs", _PROMOTED)
    def test_promoted_formula_executed(self, engine_after_5_steps, lhs):
        """manual_promoted formula is in executed_lhs after running."""
        assert lhs in engine_after_5_steps.executed_lhs, (
            f"manual_promoted formula '{lhs}' was NOT executed by the engine."
        )

    @pytest.mark.parametrize("lhs", _PROMOTED)
    def test_promoted_formula_in_store(self, engine_after_5_steps, lhs):
        """manual_promoted formula result is in the StateStore."""
        assert engine_after_5_steps.store.has(lhs), (
            f"manual_promoted formula '{lhs}' result is not in the StateStore."
        )

    def test_b_eff_positive(self, engine_after_5_steps):
        assert engine_after_5_steps.store.get("B_eff") > 0.0

    def test_capture_j_in_0_1(self, engine_after_5_steps):
        val = engine_after_5_steps.store.get("capture_j")
        assert 0.0 <= val <= 1.0

    def test_e_pulse_in_0_1(self, engine_after_5_steps):
        val = engine_after_5_steps.store.get("E_pulse")
        assert 0.0 <= val <= 1.0

    def test_e_ring_in_0_1(self, engine_after_5_steps):
        val = engine_after_5_steps.store.get("E_ring")
        assert 0.0 <= val <= 1.0

    def test_e_level_in_0_1(self, engine_after_5_steps):
        val = engine_after_5_steps.store.get("E_level")
        assert 0.0 <= val <= 1.0

    def test_all_magnetic_promoted_in_registry(self, registry):
        """All required promoted formulas exist in the V5 registry."""
        promoted_lhs = {f.lhs for f in registry.formulas if f.status == "manual_promoted"}
        required = set(self._PROMOTED)
        assert required.issubset(promoted_lhs), (
            f"Missing from registry manual_promoted: {required - promoted_lhs}"
        )

    def test_magnetic_promoted_formulas_in_stage(self, registry):
        """All required promoted formulas are in the magnetic stage."""
        mag_lhs = {
            f.lhs for f in registry.formulas
            if f.stage == "magnetic" and f.status == "manual_promoted"
        }
        assert set(self._PROMOTED).issubset(mag_lhs)



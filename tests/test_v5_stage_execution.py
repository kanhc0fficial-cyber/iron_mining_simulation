class TestV5LabelStage:
    """y_fx_xin* variables must only appear in the label step."""

    def test_y_fx_xin_in_label_stage_outputs(self, engine_after_5_steps):
        """y_fx_xin_s is produced by the label stage."""
        assert "y_fx_xin_s" in engine_after_5_steps.stage_outputs("label")

    def test_y_fx_xin_true_in_label_stage_outputs(self, engine_after_5_steps):
        """y_fx_xin_s_true is produced by the label stage."""
        assert "y_fx_xin_s_true" in engine_after_5_steps.stage_outputs("label")

    def test_y_fx_xin_NOT_in_flotation_stage_outputs(self, engine_after_5_steps):
        """y_fx_xin vars must NOT be in flotation stage outputs."""
        flotation_outputs = engine_after_5_steps.stage_outputs("flotation")
        assert "y_fx_xin_s" not in flotation_outputs, (
            "y_fx_xin_s was incorrectly produced in the flotation stage."
        )
        assert "y_fx_xin_s_true" not in flotation_outputs, (
            "y_fx_xin_s_true was incorrectly produced in the flotation stage."
        )

    def test_y_fx_xin_not_in_store_before_label_runs(self, registry):
        """Introspection: after flotation but before label step, y_fx_xin must not be set."""
        engine = V5SimulationEngine(registry)
        # Manually advance and run only up to flotation stage
        engine.store.advance()
        engine.step_time += engine._dt
        engine.step_count += 1

        stages_before_label = [
            s for s in engine.all_stage_names() if s != "label"
        ]
        for stage in stages_before_label:
            engine._run_stage(stage)

        # At this point the label stage has not run — y_fx_xin must NOT be set
        assert not engine.store.has("y_fx_xin_s"), (
            "y_fx_xin_s was set before the label stage ran."
        )
        assert not engine.store.has("y_fx_xin_s_true"), (
            "y_fx_xin_s_true was set before the label stage ran."
        )

    def test_y_fx_xin_present_after_label_step(self, registry):
        """After the label stage runs, y_fx_xin vars must be in the store."""
        engine = V5SimulationEngine(registry)
        engine.store.advance()
        engine.step_time += engine._dt
        engine.step_count += 1

        for stage in engine.all_stage_names():
            engine._run_stage(stage)

        # Now the label stage has run
        assert engine.store.has("y_fx_xin_s"), (
            "y_fx_xin_s was not set by the label stage."
        )
        assert engine.store.has("y_fx_xin_s_true"), (
            "y_fx_xin_s_true was not set by the label stage."
        )

    def test_y_fx_xin_s_value_in_0_1(self, engine_after_5_steps):
        """y_fx_xin_s (clipped output) should be in [0, 1]."""
        val = engine_after_5_steps.store.get("y_fx_xin_s")
        assert 0.0 <= val <= 1.0

    def test_y_fx_xin_s_true_matches_final_conc(self, engine_after_5_steps):
        """y_fx_xin_s_true = TFe(final_conc_s) should be a reasonable grade value."""
        val = engine_after_5_steps.store.get("y_fx_xin_s_true")
        # Should be a fraction (0–1 range), not NaN
        assert not math.isnan(val)
        assert 0.0 <= val <= 1.0

    def test_label_only_lhs_not_in_non_label_stages(self, engine_after_5_steps):
        """LABEL_ONLY_LHS vars must not appear in any non-label stage output set."""
        for stage in engine_after_5_steps.all_stage_names():
            if stage == "label":
                continue
            stage_out = engine_after_5_steps.stage_outputs(stage)
            for lhs in LABEL_ONLY_LHS:
                assert lhs not in stage_out, (
                    f"Label-only variable '{lhs}' found in non-label stage '{stage}'"
                )



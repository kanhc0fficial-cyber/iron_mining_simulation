class TestFormulaEvaluator:
    def test_evaluates_simple_expression(self, registry):
        evaluator = FormulaEvaluator(params={"B_max": 1.5, "I_exc": 10.0, "I_ref": 5.0,
                                             "T_coil": 25.0, "eps": 1e-10, "dt": 60.0})
        store = StateStore()
        formula = registry.by_lhs["B_eff"]
        result = evaluator.eval_formula(formula, store)
        assert isinstance(result, float)
        assert result > 0.0

    def test_b_eff_value_range(self, registry):
        """B_eff should be in (0, B_max] given sensible parameters."""
        evaluator = FormulaEvaluator(
            params={**DEFAULT_PARAMS, "B_max": 1.5, "I_exc": 10.0, "I_ref": 5.0, "T_coil": 25.0}
        )
        store = StateStore()
        formula = registry.by_lhs["B_eff"]
        result = evaluator.eval_formula(formula, store)
        assert 0.0 < result <= 1.5

    def test_unsupported_formula_raises(self, registry):
        """Formula with unknown name raises UnsupportedFormulaError."""
        evaluator = FormulaEvaluator(params={"dt": 60.0})
        store = StateStore()
        formula = registry.by_lhs["B_eff"]  # needs B_max, I_exc, etc.
        with pytest.raises(UnsupportedFormulaError):
            evaluator.eval_formula(formula, store)

    def test_previous_state_used(self, registry):
        """Evaluator reads X_prev from store.previous when formula references X_prev."""
        evaluator = FormulaEvaluator(params={**DEFAULT_PARAMS})
        store = StateStore()
        # T_coil = T_coil_ss + (T_coil_prev - T_coil_ss)*exp(-dt/tau_coil)
        # T_coil_prev comes from store.previous["T_coil"]
        store.set("T_coil", 30.0)
        store.advance()
        formula = registry.by_lhs["T_coil"]
        result = evaluator.eval_formula(formula, store)
        assert isinstance(result, float)
        # T_coil should be between T_coil_ss (25) and previous T_coil (30)
        assert 24.0 <= result <= 31.0

    def test_nan_rhs_returns_nan(self, registry):
        evaluator = FormulaEvaluator(params={**DEFAULT_PARAMS})
        store = StateStore()
        formula = registry.by_lhs["lab_var"]  # rhs=NaN
        result = evaluator.eval_formula(formula, store)
        assert math.isnan(result)



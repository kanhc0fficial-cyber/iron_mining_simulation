class TestV5StageCoverage:
    """Every stage must produce at least one output variable update."""

    @pytest.mark.parametrize("stage", [
        "boundary", "magnetic", "tower_mill", "flotation", "dcs", "lab", "label",
    ])
    def test_stage_has_output_variables(self, engine_after_5_steps, stage):
        outputs = engine_after_5_steps.stage_outputs(stage)
        assert len(outputs) > 0, (
            f"Stage '{stage}' has no output variable updates after 5 timesteps. "
            f"At least one formula must succeed."
        )

    def test_boundary_stage_has_ore_variables(self, engine_after_5_steps):
        outputs = engine_after_5_steps.stage_outputs("boundary")
        # At least one of the boundary ore/feed variables should be updated
        boundary_candidates = {"M_wet_i", "C_i", "M_solid_i", "TFe_i", "Fe_mag_i"}
        assert boundary_candidates & outputs, (
            f"No expected boundary variables in {outputs}"
        )

    def test_magnetic_stage_has_promoted_variables(self, engine_after_5_steps):
        outputs = engine_after_5_steps.stage_outputs("magnetic")
        promoted = {"B_eff", "E_pulse", "E_ring", "E_level", "Entr",
                    "R_hm_j", "capture_j", "conc_j", "tail_j"}
        assert promoted.issubset(outputs), (
            f"Missing magnetic promoted variables in outputs. "
            f"Present: {promoted & outputs}, Missing: {promoted - outputs}"
        )

    def test_tower_mill_stage_has_feed_variable(self, engine_after_5_steps):
        outputs = engine_after_5_steps.stage_outputs("tower_mill")
        assert "C_feed" in outputs or len(outputs) > 0

    def test_lab_stage_generates_lab_samples(self, engine_after_5_steps):
        outputs = engine_after_5_steps.stage_outputs("lab")
        assert "lab_tm_overflow_tfe" in outputs
        assert "lab_mag_mixed_conc_tfe" in outputs

    def test_label_stage_has_y_fx_xin(self, engine_after_5_steps):
        outputs = engine_after_5_steps.stage_outputs("label")
        assert "y_fx_xin_s" in outputs
        assert "y_fx_xin_s_true" in outputs


